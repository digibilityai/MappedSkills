#!/usr/bin/env node
/**
 * GATE 4 · B0 — generate the route-by-route QA inventory (Markdown) from a run folder.
 * usage: node report-routes.cjs --run <evidence dir> [--known known-defects.json] > ROUTE_QA_INVENTORY.md
 * Every number in the output comes from the run's JSON files; nothing is typed by hand.
 */
const fs = require('fs');
const path = require('path');
const { args, TEMPLATES } = require('./lib.cjs');

const a = args();
const dir = a.run;
const J = (f) => (fs.existsSync(path.join(dir, f)) ? JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')) : null);
const inv = J('inventory.json');
const known = JSON.parse(fs.readFileSync(a.known || path.join(__dirname, 'known-defects.json'), 'utf8')).defects;
const match = (pattern, fp) => { const p = pattern.split('|'), f = fp.split('|'); return p.every((x, i) => x === '*' || x === f[i] || (x.endsWith('*') && (f[i] || '').startsWith(x.slice(0, -1)))); };
const idOf = (fp) => (known.find((d) => d.patterns.some((p) => match(p, fp))) || { id: 'UNREGISTERED' }).id;
const runs = Object.fromEntries(['layout-chromium', 'layout-webkit', 'layout-firefox', 'a11y-chromium', 'a11y-webkit', 'a11y-firefox'].map((k) => [k, J(`${k}.json`)]));
const byTarget = (run, id) => {
  if (!run) return 'not run';
  const c = {};
  for (const f of run.findings.filter((x) => x.target === id)) { const k = idOf(f.fp); c[k] = (c[k] || 0) + 1; }
  const s = Object.entries(c).map(([k, n]) => `${k}×${n}`).join(' ');
  return s || '—';
};
const ldTypes = (r) => r.jsonld.map((s) => { try { const o = JSON.parse(s); return [].concat(o).map((x) => x['@type']).join('+'); } catch (e) { return '?'; } }).join(', ');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');

const out = [];
out.push(`# Gate 4 · B0 — Route-by-Route QA Inventory (generated)`);
out.push('');
out.push(`Generated by \`docs/ui-revamp/gate-4/qa/report-routes.cjs\` from \`${path.relative(process.cwd(), dir)}\` (inventory ${inv.meta.at}). **Do not edit by hand; regenerate.**`);
out.push('');
out.push('Legend: **Source** = `static` (no CMS), `empty-cms` (plain build without credentials; the empty/not-found state IS real local behaviour, not proof of CMS rendering), `fixture` (synthetic Contentful entries through the real client; see `GATE_4_B0_CMS_FIXTURE_STRATEGY.md`), `not-covered` (only the not-found / gated path could be exercised). Findings are counts per register ID (`GATE_4_B0_KNOWN_DEFECTS.md`); `—` = none. Layout findings cover 7 widths (320–1440) + text spacing + 200%/400% zoom; a11y findings cover axe, keyboard, names, reduced motion, forced colours (Chromium) and the mobile menu.');
out.push('');
out.push('## 1. Preservation snapshot (Chromium, 1440)');
out.push('');
out.push('| # | Template | Target | Source | Status | `<title>` | Canonical | Robots | JSON-LD | h1 | Headings | Main text lines | Main links | Main CTAs | Forms (fields) | Font preloads | Motion hooks | Chrome |');
out.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const r of inv.routes) {
  const ctasMain = r.ctas.filter((c) => c.startsWith('main ')).map((c) => c.split(' ')[1]);
  const cc = Object.entries(ctasMain.reduce((m, k) => ((m[k] = (m[k] || 0) + 1), m), {})).map(([k, n]) => `${k}×${n}`).join(' ') || '—';
  const forms = r.forms.map((f) => `${f.fields.filter((x) => x.tag !== 'button').length}`).join('+') || '—';
  out.push(`| ${r.n} | \`${esc(r.template)}\` | ${esc(r.id)} | ${r.cms} | ${r.status} | ${esc(r.title).slice(0, 60)} | ${r.canonical ? esc(r.canonical.replace(/^https?:\/\/[^/]+/, '') || '/ (origin)') : '—'} | ${esc(r.robots || '—')} | ${esc(ldTypes(r))} | ${r.h1count} | ${r.headings.length} | ${r.text.main.length} | ${r.links.main.length} | ${cc} | ${forms} | ${r.fontPreloads.length} | ${r.motion.dcMotion} | ${(r.chrome.header?.cls || '').includes('dc') ? 'Direction C' : 'legacy (sticky)'} |`);
}
out.push('');
out.push('## 2. Findings per target, by register ID');
out.push('');
out.push('| Target | Layout · Chromium | Layout · WebKit | Layout · Firefox | A11y · Chromium | A11y · WebKit | A11y · Firefox | Console errors (1440, Chromium) | Proof sentinels |');
out.push('|---|---|---|---|---|---|---|---|---|');
for (const r of inv.routes) {
  const sent = r.sentinels ? `withheld in HTML: ${r.sentinels.withheldInHtml.length ? r.sentinels.withheldInHtml.join(',') : 'none'}; open: ${r.sentinels.openInHtml.length}` : '—';
  out.push(`| ${esc(r.id)} | ${byTarget(runs['layout-chromium'], r.id)} | ${byTarget(runs['layout-webkit'], r.id)} | ${byTarget(runs['layout-firefox'], r.id)} | ${byTarget(runs['a11y-chromium'], r.id)} | ${byTarget(runs['a11y-webkit'], r.id)} | ${byTarget(runs['a11y-firefox'], r.id)} | ${r.errors.length} | ${sent} |`);
}
out.push('');
out.push('## 3. Keyboard and axe summary (Chromium)');
out.push('');
out.push('| Target | Tab stops 390 / 1440 | axe 390 | axe 1440 | Reduced-motion long transitions 390 / 1440 |');
out.push('|---|---|---|---|---|');
const sum = runs['a11y-chromium']?.meta.summary || {};
for (const r of inv.routes) {
  const s = sum[r.id] || {};
  out.push(`| ${esc(r.id)} | ${s.tab390 ?? '?'} / ${s.tab1440 ?? '?'} | ${(s.axe390 || []).join(' ') || '0'} | ${(s.axe1440 || []).join(' ') || '0'} | ${s.rm390 ?? '?'} / ${s.rm1440 ?? '?'} |`);
}
out.push('');
out.push('## 4. Template coverage');
out.push('');
out.push('| # | Template | Category | System | Targets | Coverage |');
out.push('|---|---|---|---|---|---|');
for (const t of TEMPLATES) {
  const rs = inv.routes.filter((r) => r.n === t.n);
  const cov = rs.every((r) => r.cms === 'static') ? 'full (static)' : rs.some((r) => r.cms === 'fixture') ? 'fixture-rendered + real empty/not-found path' : rs.some((r) => r.cms === 'not-covered') ? '**not-found / gated path only**' : 'real empty-CMS state';
  out.push(`| ${t.n} | \`${t.template}\` | ${t.cat} | ${t.system} | ${rs.map((r) => r.id).join(', ')} | ${cov}${t.targets.find((x) => x.note) ? ' — ' + t.targets.find((x) => x.note).note : ''} |`);
}
console.log(out.join('\n'));
